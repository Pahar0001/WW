/** Совместимость со старым кодом: биом = укрупнённый материал. */
export type Biome = 'sand' | 'grass' | 'forest' | 'rock' | 'snow';

/**
 * Дискретизированный рельеф. `res` — число вершин по стороне.
 * Отдаёт высоту, нормаль и уклон в любой точке с билинейной интерполяцией —
 * ровно те значения, которые видит игрок в меше.
 *
 * Строится ПОРЦИЯМИ (`buildRows`), а не в конструкторе: на высоком качестве
 * это 315 000 вершин, и синхронная сборка вешала бы вкладку на полторы
 * секунды — экран загрузки не успевал бы даже отрисоваться.
 */
export class HeightField {
  readonly res: number;
  readonly half: number;
  readonly step: number;
  readonly heights: Float32Array;
  /** Сколько строк уже построено. */
  private built = 0;

  constructor(res: number, half = WORLD.half) {
    this.res = res;
    this.half = half;
    this.step = (half * 2) / (res - 1);
    this.heights = new Float32Array(res * res);
  }

  /** Строит следующие `rows` строк. Возвращает прогресс 0..1. */
  buildRows(rows: number): number {
    const { res, half, step, heights } = this;
    const end = Math.min(res, this.built + rows);
    for (let j = this.built; j < end; j++) {
      const z = -half + j * step;
      const row = j * res;
      for (let i = 0; i < res; i++) {
        heights[row + i] = heightAt(-half + i * step, z);
      }
    }
    this.built = end;
    return end / res;
  }

  /** Достроить целиком (для тестов и мелких полей). */
  buildAll(): this {
    while (this.built < this.res) this.buildRows(64);
    return this;
  }

  get complete() {
    return this.built >= this.res;
  }

  /** Высота в мировых координатах (билинейно). За краем — дно океана. */
  sample(x: number, z: number): number {
    const { res, half, step, heights } = this;
    const fx = (x + half) / step;
    const fz = (z + half) / step;
    if (fx < 0 || fz < 0 || fx >= res - 1 || fz >= res - 1) return -14;
    const i = Math.floor(fx);
    const j = Math.floor(fz);
    const tx = fx - i;
    const tz = fz - j;
    const h00 = heights[j * res + i];
    const h10 = heights[j * res + i + 1];
    const h01 = heights[(j + 1) * res + i];
    const h11 = heights[(j + 1) * res + i + 1];
    return (h00 * (1 - tx) + h10 * tx) * (1 - tz) + (h01 * (1 - tx) + h11 * tx) * tz;
  }

  /** Нормаль поверхности (центральные разности по шагу сетки). */
  normal(x: number, z: number, out: [number, number, number] = [0, 1, 0]) {
    const e = this.step;
    const hL = this.sample(x - e, z);
    const hR = this.sample(x + e, z);
    const hD = this.sample(x, z - e);
    const hU = this.sample(x, z + e);
    const nx = hL - hR;
    const nz = hD - hU;
    const ny = 2 * e;
    const len = Math.hypot(nx, ny, nz) || 1;
    out[0] = nx / len;
    out[1] = ny / len;
    out[2] = nz / len;
    return out;
  }

  /** Уклон 0..1 (0 — горизонталь, 1 — вертикаль). */
  slope(x: number, z: number): number {
    const n = this.normal(x, z);
    return clamp01(1 - n[1]);
  }
}

