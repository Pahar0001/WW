/**
 * Влияние пути на рельеф в точке: вес 0..1 и целевая высота дна.
 *
 * Берётся БЛИЖАЙШИЙ сегмент, а не сегмент с максимальным весом. Разница
 * принципиальна: у обрыва водопада сегмент короткий, и внутренний радиус
 * сглаживания перекрывает его целиком — по «максимальному весу» побеждал
 * соседний, более длинный сегмент, и обрыв просто не вырезался.
 *
 * Отсечение по bbox — не микрооптимизация: в мире 840 × 840 м с восемью
 * тропами и тремя реками без него на каждую из 315 000 вершин приходилось бы
 * ~90 проверок сегментов, и сборка поля высот занимала бы секунды.
 */
function carve(x: number, z: number, path: Path, inner: number, outer: number) {
  if (x < path.minX || x > path.maxX || z < path.minZ || z > path.maxZ) return ZERO_CARVE;
  let bestD = Infinity;
  let bestBed = 0;
  for (const s of path.segs) {
    const wx = x - s.ax;
    const wz = z - s.az;
    const vx = s.bx - s.ax;
    const vz = s.bz - s.az;
    const t = clamp01((wx * vx + wz * vz) / s.len2);
    const cx = s.ax + vx * t;
    const cz = s.az + vz * t;
    const d = Math.hypot(x - cx, z - cz);
    if (d >= bestD) continue;
    bestD = d;
    bestBed = s.ah + (s.bh - s.ah) * t;
  }
  if (bestD > outer) return ZERO_CARVE;
  return { w: smoothstep(outer, inner, bestD), bed: bestBed };
}
const ZERO_CARVE = { w: 0, bed: 0 };

