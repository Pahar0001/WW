/**
 * Материал поверхности в точке. Единый источник правды: по нему красится меш,
 * выбирается растительность, считается сцепление в физике и звук шагов.
 *
 * Порядок проверок — от безусловного к «по умолчанию»: лава и вода не зависят
 * от зоны, снег и лёд определяются высотой, скала — уклоном, и лишь в конце
 * слово получает материал зоны.
 */
export function surfaceAt(x: number, z: number, h: number, slope: number): Surface {
  if (lavaAt(x, z)) return 'lava';

  const zone = zoneAt(x, z);

  // Кромка воды — всегда песок или галька, независимо от зоны.
  if (h < WORLD.beach) return zone.id === 'volcano' ? 'ash' : 'sand';

  // Снеговая линия зависит от зоны: на леднике снег лежит вдвое ниже, чем
  // на южных плато той же высоты. Без этого ледник выглядит как обычная гора.
  const snowLine = zone.id === 'glacier' ? 58 : zone.id === 'ridge' ? 96 : 118;
  if (h > snowLine && slope < 0.58) {
    // На крутых наветренных склонах ледника снег сдут — обнажается лёд.
    return zone.id === 'glacier' && slope > 0.3 ? 'ice' : 'snow';
  }

  if (slope > 0.5) return zone.id === 'canyon' ? 'clay' : 'rock';

  if (zone.id === 'desert') return 'dune';
  if (zone.id === 'volcano') return h > 60 ? 'ash' : 'gravel';
  if (zone.id === 'canyon') return 'clay';
  if (zone.id === 'ruins') return 'gravel';
  if (zone.id === 'jungle' && h > 8) return 'forest';
  if (zone.id === 'glacier') return 'gravel';

  // Лес растёт в средних высотах на пологом — там, где ему и положено.
  if (h > 10 && h < 78 && slope < 0.32) return 'forest';
  return 'grass';
}

/** Укрупнение материала до старого типа `Biome` — для кода, который его ждёт. */
export function biomeAt(h: number, slope: number, x = 0, z = 0): Biome {
  const s = surfaceAt(x, z, h, slope);
  switch (s) {
    case 'sand':
    case 'dune':
      return 'sand';
    case 'snow':
    case 'ice':
      return 'snow';
    case 'rock':
    case 'clay':
    case 'gravel':
    case 'ash':
    case 'lava':
      return 'rock';
    case 'forest':
      return 'forest';
    default:
      return 'grass';
  }
}

