/**
 * Уровень жидкости в точке: 0 — океан, иначе зеркало ближайшей чаши.
 * Живёт здесь, а не в контроллере: тем же ответом пользуются вода, лодка,
 * рыба и правило «в лаву нельзя».
 */
export function waterLevelAt(x: number, z: number): number {
  for (const b of BASINS) {
    if (Math.hypot(x - b.x, z - b.z) < b.r * 1.06) return b.level;
  }
  return 0;
}

/** Стоит ли игрок в лаве — отдельный вопрос: последствия другие. */
export function lavaAt(x: number, z: number): boolean {
  for (const b of BASINS) {
    if (b.kind === 'lava' && Math.hypot(x - b.x, z - b.z) < b.r * 1.06) return true;
  }
  return false;
}

