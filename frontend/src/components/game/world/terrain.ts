/**
 * Геометрия мира Vela — вся математика ландшафта в одном месте.
 *
 * Ключевое решение (не менять, не разобравшись): рельеф считается на CPU один
 * раз и живёт в Float32Array (HeightField). И меш, и физика персонажа, и
 * расстановка деревьев, и мини-карта читают ОДНО И ТО ЖЕ поле высот с
 * билинейной интерполяцией — поэтому герой стоит ровно на видимой поверхности.
 * Если бы физика семплировала шум напрямую, между вершинами сетки (меш там —
 * плоский треугольник) персонаж то проваливался бы, то парил.
 *
 * Шум — собственный, детерминированный по целочисленному хешу: одинаковый мир
 * на всех устройствах и при каждом заходе, без Math.random и без скачивания
 * карт высот.
 *
 * Мир состоит из ЗОН (`ZONES`). Зона — это не декорация, а набор параметров
 * рельефа: базовая высота, амплитуда скал, частота холмов, материал
 * поверхности, палитра. Высота в точке — взвешенная смесь параметров зон,
 * поверх которой ложатся рукотворные объекты: хребты, кальдеры, каньон, дюны,
 * реки, тропы и площадки.
 */

// ── Шум ────────────────────────────────────────────────────────────────

/** Целочисленный хеш → 0..1. Три умножения-сдвига дают достаточно «белый» шум. */
function hash(x: number, y: number): number {
  let h = x * 374761393 + y * 668265263;
  h = (h ^ (h >> 13)) * 1274126177;
  h = h ^ (h >> 16);
  // >>> 0 — приводим к беззнаковому, иначе на отрицательных координатах
  // получаются отрицательные «вероятности» и рельеф рвётся.
  return (h >>> 0) / 4294967295;
}

/** Градиент в узле решётки (единичный вектор из хеша). */
function grad(ix: number, iy: number, dx: number, dy: number): number {
  const a = hash(ix, iy) * Math.PI * 2;
  return Math.cos(a) * dx + Math.sin(a) * dy;
}

const fade = (t: number) => t * t * t * (t * (t * 6 - 15) + 10);

/** Градиентный шум Перлина, −1..1. */
export function noise2(x: number, y: number): number {
  const ix = Math.floor(x);
  const iy = Math.floor(y);
  const fx = x - ix;
  const fy = y - iy;
  const u = fade(fx);
  const v = fade(fy);

  const n00 = grad(ix, iy, fx, fy);
  const n10 = grad(ix + 1, iy, fx - 1, fy);
  const n01 = grad(ix, iy + 1, fx, fy - 1);
  const n11 = grad(ix + 1, iy + 1, fx - 1, fy - 1);

  const nx0 = n00 + u * (n10 - n00);
  const nx1 = n01 + u * (n11 - n01);
  return (nx0 + v * (nx1 - nx0)) * 1.4;
}

/** Фрактальный шум (сумма октав), примерно −1..1. */
export function fbm(x: number, y: number, octaves = 5, lacunarity = 2.03, gain = 0.5): number {
  let sum = 0;
  let amp = 1;
  let norm = 0;
  let fx = x;
  let fy = y;
  for (let i = 0; i < octaves; i++) {
    sum += noise2(fx, fy) * amp;
    norm += amp;
    amp *= gain;
    fx *= lacunarity;
    fy *= lacunarity;
    // Поворот сетки между октавами убирает характерные «клетки» Перлина.
    const t = fx;
    fx = t * 0.8 - fy * 0.6;
    fy = t * 0.6 + fy * 0.8;
  }
  return sum / norm;
}

/**
 * Хребтовой шум: |noise| перевёрнутый и возведённый в степень — даёт острые
 * гребни и осыпающиеся склоны вместо круглых холмов fbm. 0..1.
 */
export function ridged(x: number, y: number, octaves = 5): number {
  let sum = 0;
  let amp = 0.5;
  let norm = 0;
  let fx = x;
  let fy = y;
  let prev = 1;
  for (let i = 0; i < octaves; i++) {
    const n = 1 - Math.abs(noise2(fx, fy));
    const r = n * n * prev;
    sum += r * amp;
    norm += amp;
    prev = r;
    amp *= 0.52;
    fx *= 2.07;
    fy *= 2.07;
  }
  return sum / norm;
}

const clamp01 = (v: number) => (v < 0 ? 0 : v > 1 ? 1 : v);
const smoothstep = (e0: number, e1: number, x: number) => {
  const t = clamp01((x - e0) / (e1 - e0 || 1));
  return t * t * (3 - 2 * t);
};
const lerp = (a: number, b: number, t: number) => a + (b - a) * t;

