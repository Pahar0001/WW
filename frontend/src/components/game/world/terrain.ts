/** Предрасчёт сегментов пути: нормаль, длина и bbox, чтобы не считать это в цикле. */
type Seg = { ax: number; az: number; bx: number; bz: number; ah: number; bh: number; len2: number };
type Path = { segs: Seg[]; minX: number; maxX: number; minZ: number; maxZ: number };

function buildPath(nodes: PathNode[], pad: number): Path {
  const segs: Seg[] = [];
  let minX = Infinity;
  let maxX = -Infinity;
  let minZ = Infinity;
  let maxZ = -Infinity;
  for (let i = 0; i < nodes.length - 1; i++) {
    const [ax, az, ah] = nodes[i];
    const [bx, bz, bh] = nodes[i + 1];
    const vx = bx - ax;
    const vz = bz - az;
    segs.push({ ax, az, bx, bz, ah, bh, len2: vx * vx + vz * vz || 1 });
    minX = Math.min(minX, ax, bx);
    maxX = Math.max(maxX, ax, bx);
    minZ = Math.min(minZ, az, bz);
    maxZ = Math.max(maxZ, az, bz);
  }
  return { segs, minX: minX - pad, maxX: maxX + pad, minZ: minZ - pad, maxZ: maxZ + pad };
}

/** Предельный уклон тропы, к которому стремится грейдер (tan угла). */
const TRAIL_MAX_GRADE = 0.62;

/**
 * «Грейдер»: выравнивает профили ВСЕХ троп так, чтобы уклон между соседними
 * узлами не превышал TRAIL_MAX_GRADE.
 *
 * Тропы выравниваются СЕТЬЮ, а не по одной. Развилки (а их семь: тропы
 * ветвятся от магистрали) в разных трассах записаны одной и той же парой
 * координат. Пока каждая трасса выравнивалась отдельно, в общей точке они
 * приходили к РАЗНЫМ высотам — одна считала перекрёсток на отметке 133, другая
 * на 108. Оба полотна врезались в рельеф рядом друг с другом, и на стыке
 * возникала ступень в 25 метров: уклон 65° там, где на карте обычная развилка.
 * Здесь узел с общими координатами — один узел, и высота у него ровно одна.
 *
 * Неподвижные опоры: узлы с явно заданной высотой (перевалы, настилы мостов,
 * броды) и одиночные концы трасс — их смысл в том, чтобы попасть в конкретную
 * точку. Остальные подтягиваются навстречу друг другу, как при отсыпке дороги:
 * выемка сверху, подсыпка снизу. Терраформинг ниже (carve) приведёт рельеф к
 * этому профилю, поэтому тропа не повиснет в воздухе.
 */
type GradeNode = { x: number; z: number; h: number; fixed: boolean; uses: number };

function gradeTrails(trails: PathNode[][]): PathNode[][] {
  const key = (x: number, z: number) => `${Math.round(x)},${Math.round(z)}`;
  const index = new Map<string, number>();
  const nodes: GradeNode[] = [];
  const refs: number[][] = [];

  for (const trail of trails) {
    const row: number[] = [];
    for (const [x, z, h] of trail) {
      const k = key(x, z);
      let n = index.get(k);
      if (n === undefined) {
        n = nodes.length;
        index.set(k, n);
        nodes.push({
          x,
          z,
          h: Number.isNaN(h) ? heightWithWater(x, z) : h,
          fixed: !Number.isNaN(h),
          uses: 0,
        });
      } else if (!Number.isNaN(h)) {
        // Явно заданная высота на развилке побеждает подобранную по рельефу.
        nodes[n].h = h;
        nodes[n].fixed = true;
      }
      nodes[n].uses++;
      row.push(n);
    }
    refs.push(row);
  }

  // Конец трассы закрепляем, только если он не развилка: иначе перекрёсток
  // окажется зажат и грейдер не сможет разгладить подход к нему.
  for (const row of refs) {
    for (const i of [row[0], row[row.length - 1]]) {
      if (nodes[i].uses === 1) nodes[i].fixed = true;
    }
  }

  // Длины сегментов считаем один раз: они не меняются, двигаем только высоту.
  const links: { a: number; b: number; len: number }[] = [];
  for (const row of refs) {
    for (let i = 0; i < row.length - 1; i++) {
      const a = nodes[row[i]];
      const b = nodes[row[i + 1]];
      links.push({ a: row[i], b: row[i + 1], len: Math.hypot(b.x - a.x, b.z - a.z) || 1 });
    }
  }

  for (let pass = 0; pass < 220; pass++) {
    let worst = 0;
    for (const l of links) {
      const A = nodes[l.a];
      const B = nodes[l.b];
      const dh = B.h - A.h;
      const over = Math.abs(dh) - l.len * TRAIL_MAX_GRADE;
      if (over <= 0.001) continue;
      worst = Math.max(worst, over);
      if (A.fixed && B.fixed) continue;
      const sign = Math.sign(dh);
      const shareA = A.fixed ? 0 : B.fixed ? 1 : 0.5;
      const shareB = B.fixed ? 0 : A.fixed ? 1 : 0.5;
      A.h += sign * over * shareA * 0.6;
      B.h -= sign * over * shareB * 0.6;
    }
    if (worst < 0.01) break;
  }

  return refs.map((row) => row.map((n) => [nodes[n].x, nodes[n].z, nodes[n].h] as PathNode));
}

