/** Веса зон в точке. Переиспользуемый буфер: функция зовётся 300 000 раз. */
const zw = new Float32Array(ZONES.length);

/**
 * Вес каждой зоны в точке, нормированный к сумме 1.
 * Возвращает общий буфер — копировать, если нужно сохранить.
 */
export function zoneWeights(x: number, z: number): Float32Array {
  let sum = 0;
  for (let i = 0; i < ZONES.length; i++) {
    const zn = ZONES[i];
    const d = Math.hypot(x - zn.center[0], z - zn.center[1]);
    // Влияние тянется до 1.45 радиуса: переходная полоса шириной ~60 м.
    const w = d > zn.r * 1.45 ? 0 : smoothstep(zn.r * 1.45, zn.r * 0.5, d);
    zw[i] = w;
    sum += w;
  }
  if (sum < 1e-4) {
    // Вне влияния всех зон (дальний шельф) — считаем лугом.
    zw.fill(0);
    zw[ZONES.length - 1] = 1;
    return zw;
  }
  for (let i = 0; i < ZONES.length; i++) zw[i] /= sum;
  return zw;
}

/** Доминирующая зона в точке — для музыки, погоды, подписи на компасе. */
export function zoneAt(x: number, z: number): Zone {
  const w = zoneWeights(x, z);
  let best = 0;
  for (let i = 1; i < ZONES.length; i++) if (w[i] > w[best]) best = i;
  return ZONES[best];
}

/**
 * Маска суши: сумма гауссиан метаболов с порогом, промодулированная шумом.
 * 0 — открытое море, 1 — глубина материка.
 */
function landMask(x: number, z: number): number {
  let f = 0;
  for (const b of LANDMASS) {
    const dx = x - b.x;
    const dz = z - b.z;
    const d2 = dx * dx + dz * dz;
    const r2 = b.r * b.r;
    if (d2 >= r2) continue; // компактный носитель: за радиусом ровно ноль
    const k = 1 - d2 / r2;
    f += b.w * k * k * k;
  }
  // Шум ломает окружности блобов: заливы, косы и рваные мысы.
  f += fbm(x * 0.0042 + 11, z * 0.0042 - 7, 4) * 0.13;
  return smoothstep(LAND_LEVEL, LAND_LEVEL + 0.2, f);
}

/**
 * Аналитическая высота рельефа — без рек, троп и площадок.
 *
 * Слои складываются осознанно, а не «шум и хватит»:
 *  1. маска суши из метаболов;
 *  2. смесь параметров зон — базовая высота, скалистость, холмы;
 *  3. рукотворные хребты вдоль заданных осей;
 *  4. дюны в пустыне (направленные валы, а не изотропный шум);
 *  5. кальдеры: вал наружу, плоское дно внутрь;
 *  6. каньон, врезанный в плато;
 *  7. выполаживание пляжа у самой воды.
 */
function heightBase(x: number, z: number): number {
  const mask = landMask(x, z);
  if (mask <= 0.0001) return -14; // дно океана — сразу и без вычислений

  // 2. Смесь зон.
  const w = zoneWeights(x, z);
  let base = 0;
  let ridgeAmp = 0;
  let hillAmp = 0;
  let freq = 0;
  let detailAmp = 0;
  for (let i = 0; i < ZONES.length; i++) {
    const k = w[i];
    if (k < 0.001) continue;
    const zn = ZONES[i];
    base += zn.base * k;
    ridgeAmp += zn.ridge * k;
    hillAmp += zn.hills * k;
    freq += zn.freq * k;
    detailAmp += zn.detail * k;
  }

  const hills = (fbm(x * freq, z * freq, 5) * 0.5 + 0.5) * hillAmp;
  const rock = ridged(x * freq * 1.15 + 3, z * freq * 1.15 + 19, 5);
  const detail = fbm(x * 0.055, z * 0.055, 3) * detailAmp;

  let h = base + hills + ridgeAmp * rock + detail;

  // 3. Хребты: падение высоты от оси × профиль вдоль оси × хребтовой шум.
  for (const s of SPINES) {
    const seg = distToSegment(x, z, s.a[0], s.a[1], s.b[0], s.b[1]);
    if (seg.d > s.width) continue;
    const across = smoothstep(s.width, s.width * 0.06, seg.d);
    // У концов хребет ниже, в середине — главная вершина.
    const along = 0.44 + 0.56 * Math.sin(seg.t * Math.PI);
    const grain = ridged(x * 0.013 + 41, z * 0.013 - 17, 5);
    h = smax(h, across * along * s.height * (0.46 + grain * 0.54), 7);
  }

  // 4. Дюны: направленные валы. Изотропный шум читается как «холмы в песке»,
  //    а не как пустыня — барханы всегда выстроены поперёк ветра.
  const dune = w[6]; // индекс зоны desert в ZONES
  if (dune > 0.02) {
    const ang = 0.72; // направление господствующего ветра
    const u = x * Math.cos(ang) + z * Math.sin(ang);
    const wave = Math.sin(u * 0.055 + fbm(x * 0.006, z * 0.006, 3) * 3.1);
    // Крутая подветренная сторона: возведение в степень делает вал несимметричным.
    h += dune * (Math.pow(wave * 0.5 + 0.5, 1.7) * 13 - 4);
  }

  h *= mask;

  // 5. Кальдеры. Внутри вала рельеф ЗАМЕНЯЕТСЯ плоским дном, а не
  //    «продавливается» пропорционально: при пропорциональном вычитании чаша
  //    получается узкой воронкой, и озеро наливается лужей вместо озера.
  for (const b of BASINS) {
    const dl = Math.hypot(x - b.x, z - b.z);
    if (dl > b.r * 2) continue;
    // Вал: в кольцевой полосе высота подтягивается ВВЕРХ до гребня, но никогда
    // не опускается — на равнине вал просто вырастает, на склоне «достраивает»
    // только подгорную сторону, и чаша оказывается замкнутой в обоих случаях.
    const rim = smoothstep(b.r * 1.75, b.r * 1.14, dl) * (1 - smoothstep(b.r * 1.1, b.r * 0.94, dl));
    if (rim > 0) {
      const crest = b.level + b.rimUp;
      if (crest > h) h = h + (crest - h) * rim;
    }
    const bowl = smoothstep(b.r * 1.05, b.r * 0.62, dl);
    const floorH = b.level - b.depth + fbm(x * 0.05 + 5, z * 0.05 - 3, 2) * 0.9;
    h = h * (1 - bowl) + floorH * bowl;
  }

  // 6. Каньон: узкое дно, отвесные стены. Вырезается ДО рек, потому что это
  //    русло высохшей реки — по нему потом можно пройти насквозь.
  const cn = carve(x, z, canyonPath(), 11, 42);
  if (cn.w > 0 && cn.bed < h) {
    // Степень 2.4 превращает мягкий smoothstep в почти отвесную стену.
    const wall = Math.pow(cn.w, 0.42);
    h = h * (1 - wall) + cn.bed * wall;
  }

  // 7. Пляж: у воды рельеф выполаживается, иначе берег выглядит обрубленным.
  const beachBlend = smoothstep(0.16, 0.42, mask);
  h *= 0.2 + 0.8 * beachBlend;

  // Ниже нуля уходим полого — это подводный склон, а не стена.
  return h < 0 ? h * 2.2 : h;
}

/** Рельеф с площадками и реками, но без троп — основа для «самоукладки» троп. */
function heightWithWater(x: number, z: number): number {
  let h = heightBase(x, z);

  // Площадки выравнивают рельеф до троп, иначе тропа «ложилась бы на землю»
  // до выравнивания и повисала бы над готовой площадкой.
  for (const f of FLATS) {
    const d = Math.hypot(x - f.x, z - f.z);
    if (d > f.blend) continue;
    const w = smoothstep(f.blend, f.r, d);
    const target = f.h ?? heightBase(f.x, f.z);
    h = h * (1 - w) + target * w;
  }

  for (const p of riverPaths()) {
    const r = carve(x, z, p, 5.5, 17);
    // Русло не «подсыпает» рельеф: вода не может течь выше берега.
    if (r.w > 0 && r.bed < h) h = h * (1 - r.w) + r.bed * r.w;
  }
  return h;
}

/** Итоговая высота: рельеф + площадки + русла + тропы. */
export function heightAt(x: number, z: number): number {
  let h = heightWithWater(x, z);

  // Полотна СМЕШИВАЮТСЯ по весам, а не накладываются друг на друга по очереди.
  // У развилки два коридора перекрываются; при последовательном наложении
  // побеждала та трасса, что стоит в массиве позже, и её полотно — на десяток
  // метров в стороне от своей оси — перебивало полотно первой. На подъёме к
  // вершине это давало провал на два метра и следом стенку в 61°, хотя обе
  // тропы в самой точке развилки согласованы до сантиметра (см. gradeTrails).
  let wSum = 0;
  let bedSum = 0;
  for (const p of trailPaths()) {
    const t = carve(x, z, p, 4, 15);
    if (t.w <= 0) continue;
    wSum += t.w;
    bedSum += t.bed * t.w;
  }
  if (wSum > 0) {
    const w = wSum > 1 ? 1 : wSum;
    h = h * (1 - w) + (bedSum / wSum) * w;
  }
  // Русла восстанавливаем ПОСЛЕ троп узким проходом: там, где тропа переходит
  // реку, она иначе засыпала бы брод и превратила его в плотину — вода
  // визуально текла бы в гору.
  for (const p of riverPaths()) {
    const ford = carve(x, z, p, 3.4, 8.5);
    if (ford.w > 0 && ford.bed < h) h = h * (1 - ford.w) + ford.bed * ford.w;
  }
  return h;
}

/** Насколько точка «на тропе» (0..1) — для цвета грунта и запрета растительности. */
export function trailWeight(x: number, z: number): number {
  let w = 0;
  for (const p of trailPaths()) {
    const t = carve(x, z, p, 3, 9.5);
    if (t.w > w) w = t.w;
  }
  return w;
}

/** Насколько точка в русле реки (0..1) — вода и галька вместо травы. */
export function riverWeight(x: number, z: number): number {
  let w = 0;
  for (const p of riverPaths()) {
    const t = carve(x, z, p, 3.8, 10);
    if (t.w > w) w = t.w;
  }
  return w;
}

