/**
 * Регионы мира Vela и артефакты.
 *
 * Каждое место — это не просто точка на карте, а вход в реальный раздел сайта:
 * игра работает как объёмное оглавление Vela. Открыв «Бухту Зари», игрок
 * получает ссылку на коллекцию маршрутов, «Руины Картографов» ведут к
 * ИИ-консьержу и так далее. Тексты — про путешествия, а не про игру.
 *
 * Координаты заданы в плоскости XZ; высота берётся из рельефа во время
 * загрузки — так метки всегда лежат на поверхности, даже если рельеф подкрутят.
 *
 * ⚠️ Центр региона обязан быть местом, где можно СТОЯТЬ. Для водоёмов и жерла
 * это берег и гребень, а не геометрический центр: карточка открытия
 * срабатывает по расстоянию, и метка, поставленная в воду, либо недостижима,
 * либо заставляет игрока плыть к «достопримечательности».
 */

import type { ZoneId } from './world/terrain';

export type Region = {
  id: string;
  /** Название региона. */
  name: string;
  /** Короткая типологическая подпись (эйбрау). */
  kind: string;
  /** Описание, которое читается в карточке открытия. */
  description: string;
  /** Куда ведёт раздел Vela. */
  href: string;
  cta: string;
  /** Центр в мировых координатах XZ. */
  at: [number, number];
  /** Радиус обнаружения. */
  radius: number;
  /** Зона рельефа, к которой привязан регион (музыка, погода, палитра). */
  zone: ZoneId;
  /** Скрытое место — не показывается на карте, пока не найдено. */
  secret?: boolean;
  /** Цвет метки/свечения. */
  tone: string;
  /**
   * Настоящие направления с таким же ландшафтом.
   *
   * Ради этого игра и стоит на сайте: открыв вымышленный ледник, человек
   * получает предложение съездить на настоящий. Слаги — из каталога стран,
   * чтобы ссылки вели в живые разделы, а не в никуда.
   */
  realWorld?: {
    /** Чем это место является в реальном мире. */
    theme: string;
    /** Слаги стран каталога — от самого близкого по ощущению. */
    countries: string[];
  };
};

