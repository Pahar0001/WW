/**
 * Сюжет мира Vela: главы, фрагменты Карты Мира и дневник путешественника.
 *
 * Замысел. Когда-то Орден Картографов чертил карту всего обитаемого мира —
 * не для торговли и не для войны, а чтобы никто больше не считал соседнюю
 * страну краем земли. Карту разорвало вместе с Орденом; её части унесли по
 * разным землям вместе с приборами путешественников. Игрок собирает Карту
 * Мира Vela обратно: восемь фрагментов, по одному на регион.
 *
 * Почему так, а не «собери 100 монеток»: у игрока должна быть ОДНА понятная
 * цель, которая объясняет, зачем идти в пустыню и на ледник, и при этом
 * рифмуется с самим сайтом — Vela про то, что мир больше, чем кажется.
 *
 * Тексты — про путешествия и людей, а не про игровые механики. Ни одного
 * «получите +10 к опыту»: игра встроена в сайт о реальных поездках, и
 * геймерский жаргон выбивал бы её из этого контекста.
 *
 * Данные ЗДЕСЬ, логика — в `quests.ts` и `state.ts`. Этот файл читается как
 * сценарий, и правки в нём не требуют понимания движка.
 */

