/**
 * Реквизиты оператора персональных данных — ЕДИНСТВЕННОЕ место, куда их нужно
 * вписать. Отсюда они подставляются во все три документа и в письма.
 *
 * ⚠️ Пока значения начинаются с «{{» — это заглушки. 152-ФЗ (ст. 18.1 ч. 2 п. 2)
 * требует, чтобы политика называла оператора и его контакты; документ с
 * заглушками юридической силы не имеет. Поэтому, пока они не заменены,
 * страницы показывают заметное предупреждение — иначе такое уедет на прод
 * незамеченным.
 *
 * Что вписать:
 *   name      «ИП Иванов Иван Иванович» или «ООО "Вела"»
 *   inn       ИНН оператора
 *   ogrn      ОГРН для организации, ОГРНИП для предпринимателя
 *   address   адрес, по которому оператора можно найти официально
 *
 * После заполнения — поднять версии документов в `versions.ts` (и в
 * `backend/src/modules/legal/versions.ts`): меняется существенное условие,
 * согласия нужно собрать заново.
 */
export const OPERATOR = {
  name: '{{ОПЕРАТОР_НАИМЕНОВАНИЕ}}',
  inn: '{{ИНН}}',
  ogrn: '{{ОГРН}}',
  address: '{{АДРЕС}}',
  /** Общий адрес поддержки — он же для обращений по персональным данным. */
  email: 'support@velatrips.ru',
  /** Отдельный ящик для запросов по ПДн (отзыв согласия, удаление, доступ). */
  privacyEmail: 'privacy@velatrips.ru',
  site: 'velatrips.ru',
  siteUrl: 'https://velatrips.ru',
} as const;

/** Реквизиты заполнены? Заглушки узнаём по «{{» в начале. */
export const OPERATOR_FILLED = !Object.values(OPERATOR).some((v) => v.startsWith('{{'));

/**
 * Оператор одной строкой для текста документов: «ИП … (ИНН …, ОГРНИП …), адрес …».
 * Пустые (незаполненные) реквизиты не выбрасываем — наоборот, они должны быть
 * видны в тексте, чтобы заглушку было невозможно не заметить.
 */
export const operatorLine = (): string =>
  `${OPERATOR.name} (ИНН ${OPERATOR.inn}, ОГРН ${OPERATOR.ogrn}), адрес: ${OPERATOR.address}`;
