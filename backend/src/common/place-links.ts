/**
 * Ссылки на места — ТОЛЬКО те форматы, которые открывали руками и видели данные.
 *
 * ⚠️ Этот файл появился после того, как владелец ткнул в ссылку на отель и
 * получил пустую форму поиска. Разбор показал, что мёртвыми были ВСЕ ссылки на
 * бронирование, причём в четырёх местах кода сразу, — их сочиняли по памяти,
 * потому что адрес выглядит правдоподобно и никто его не открывает.
 *
 * Что выяснилось при проверке в настоящем браузере (curl тут бесполезен, см.
 * ниже):
 *
 *   ✗ ostrovok.ru/hotels/?q=…        — «Ошибка 404». Поиск у них идёт через
 *                                      автокомплит с внутренними ID, текстовой
 *                                      ссылки не существует вовсе.
 *   ✗ ostrovok.ru/hotel/search/?q=…  — 404 (этот адрес стоял в коде до нас).
 *   ✗ travel.yandex.ru/hotels/?text= — открывается ПУСТАЯ форма: параметр
 *                                      игнорируется. Поиск требует geoId.
 *   ✗ booking.com/searchresults?ss=  — сбрасывает запрос и уводит на главную.
 *   ~ google.com/travel/search?q=    — знает только крупные сети. «Novotel»
 *                                      находит, «Air Express Sheremetyevo» —
 *                                      «Ничего не найдено». Для справочника из
 *                                      OSM, где половина отелей мелкие, не
 *                                      годится: половина ссылок вела бы в тупик.
 *   ✓ yandex.ru/maps + whatshere     — открывает карточку ИМЕННО этой точки по
 *                                      координатам. Работает всегда, потому что
 *                                      координата — это не название, её не надо
 *                                      искать в чужой базе.
 *   ✓ yandex.ru/maps + text          — поиск «отели рядом с аэропортом X» даёт
 *                                      живой список с рейтингами и ценами.
 *
 * ⚠️ ПРОВЕРЯТЬ ТОЛЬКО В БРАУЗЕРЕ. `curl` отдаёт 200 и на мёртвый адрес: у SPA
 * страница «не найдено» рисуется скриптом уже после загрузки. Именно поэтому
 * первая правка Ostrovok прошла «проверку» и всё равно была мёртвой.
 * Скрипт `scripts/check-links.ts` ловит только грубые случаи — он не заменяет
 * браузер, и в нём об этом написано.
 */

/** Координаты у Яндекса идут долгота, широта — перепутать их легко и незаметно. */
const ll = (lat: number, lng: number) => `${lng.toFixed(6)},${lat.toFixed(6)}`;

/**
 * Карточка конкретного места по координатам.
 *
 * Режим `whatshere` открывает панель «что здесь» ровно в этой точке: адрес,
 * организации в здании, отзывы, а для отелей — предложения о бронировании.
 * Название в ссылку НЕ кладём: текстовый поиск может промахнуться (проверено —
 * по запросу «Air Express Sheremetyevo» Яндекс первым показал карго-центр),
 * а координата из OSM указывает на здание однозначно.
 */
export function mapPointUrl(lat: number, lng: number): string {
  const p = ll(lat, lng);
  return (
    `https://yandex.ru/maps/?ll=${p}&z=18` +
    `&whatshere%5Bpoint%5D=${p}&whatshere%5Bzoom%5D=18`
  );
}

/**
 * Поиск мест вокруг точки: «отели рядом с аэропортом Шереметьево».
 * Отдаёт живой список с рейтингами, ценами и кнопкой бронирования.
 */
export function mapSearchUrl(query: string, lat?: number, lng?: number, zoom = 14): string {
  const base = `https://yandex.ru/maps/?text=${encodeURIComponent(query)}`;
  return lat !== undefined && lng !== undefined ? `${base}&ll=${ll(lat, lng)}&z=${zoom}` : base;
}

